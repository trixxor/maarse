#!/usr/bin/env python3
"""Generate docs/reference/settings.md from the host's own --help text.

Usage: python tools/gen_settings_reference.py [path-to-maarse-host] [--check]

The settings reference is generated, never edited by hand, so it cannot drift
from the code. With --check the script exits 1 if the committed file differs
from what the current binary would produce (used by CI).
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference" / "settings.md"


def host_binary(args):
    for a in args:
        if not a.startswith("--"):
            return a
    for cand in ("target/release/maarse-host", "target/debug/maarse-host",
                 "target/release/maarse-host.exe", "target/debug/maarse-host.exe"):
        if (ROOT / cand).exists():
            return str(ROOT / cand)
    sys.exit("maarse-host binary not found: build it with `cargo build -p maarse-host`")


def parse(help_text):
    """Return a list of (option line, description) pairs."""
    opts, cur = [], None
    for line in help_text.splitlines():
        m = re.match(r"^  (--[a-z0-9-]+)(.*)$", line)
        if m:
            if cur:
                opts.append(cur)
            rest = m.group(2)
            # "--opt <value>   text" -> split the synopsis from the text at 2+ spaces
            parts = re.split(r"\s{2,}", rest.strip(), maxsplit=1)
            arg = parts[0] if parts and parts[0].startswith(("<", "[")) else ""
            text = parts[1] if len(parts) > 1 else (parts[0] if parts and not arg else "")
            cur = [m.group(1), arg, [text] if text else []]
        elif cur and line.startswith("    ") and line.strip():
            cur[2].append(line.strip())
        elif cur and not line.strip():
            opts.append(cur)
            cur = None
    if cur:
        opts.append(cur)
    return [(f"{o[0]} {o[1]}".strip(), " ".join(o[2])) for o in opts]


def render(opts):
    out = [
        "<!-- GENERATED by tools/gen_settings_reference.py from `maarse-host --help`. Do not edit by hand. -->",
        "",
        "# Settings reference",
        "",
        "> **Type:** reference · **Status:** released (generated from the code)",
        "",
        "Every option of `maarse-host` and `maarse-server`. **The primary way to change them is the "
        "web client (Settings tab, or Settings page in the Android app).** Saving there writes "
        "`settings.txt` in the data folder and restarts the host. You can also edit `settings.txt` "
        "by hand: one option per line, exactly as listed below, for example:",
        "",
        "```text",
        "--public-addr server.example.org:4242",
        "--region dk",
        "--mail-quota-mb 500",
        "```",
        "",
        "Lines starting with `#` are comments. `settings.txt` is read first; options given on the "
        "command line (for example in a start script) win. `--data` and `--help` are not allowed in "
        "the file. Command-line use exists for the very first start and for scripts; it is not the "
        "recommended way to configure a running host.",
        "",
        "Back to the [documentation index](../index.md) · "
        "How-to: [run a host or server](../guides/run-a-server.md)",
        "",
        "| Option | What it does |",
        "| --- | --- |",
    ]
    for syn, desc in opts:
        cell = desc.replace("|", "\\|")
        out.append(f"| `{syn}` | {cell} |")
    out.append("")
    return "\n".join(out)


def main():
    args = sys.argv[1:]
    exe = host_binary(args)
    help_text = subprocess.run([exe, "--help"], capture_output=True, text=True).stdout
    opts = parse(help_text)
    if len(opts) < 20:
        sys.exit(f"parsed only {len(opts)} options; the help format changed?")
    text = render(opts)
    if "--check" in args:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/reference/settings.md is out of date: run tools/gen_settings_reference.py")
            sys.exit(1)
        print("settings reference is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(opts)} options)")


if __name__ == "__main__":
    main()
