<#
.SYNOPSIS
    Runs maarse-host at Windows startup and restarts it when it exits.

.DESCRIPTION
    Copies maarse-host.exe to an install folder, writes a small supervisor
    script next to it and registers a Scheduled Task that starts the
    supervisor at boot. The supervisor runs "maarse-host --service" in a loop:
    if the host exits with a non-zero code (a crash, or code 75 after settings
    were changed in the web client) it is started again after a short delay.
    The task runs as SYSTEM, so no user has to be logged in.

    Run from an elevated PowerShell:
      .\packaging\windows\install-service.ps1 -Exe .\target\release\maarse-host.exe -HostArgs '--serial COM6'
    Remove again:
      .\packaging\windows\install-service.ps1 -Uninstall

.PARAMETER Exe
    Path to maarse-host.exe (default: target\release\maarse-host.exe).
.PARAMETER InstallDir
    Where the exe and supervisor are installed (default: C:\Program Files\maarse-host).
.PARAMETER DataDir
    Data folder for identity, settings and history (default: C:\ProgramData\maarse-host).
.PARAMETER HostArgs
    Extra command-line options for maarse-host, e.g. '--serial COM6 --peer host:4242'.
.PARAMETER TaskName
    Name of the Scheduled Task (default: maarse-host).
.PARAMETER Tray
    Also install maarse-tray.exe (from -TrayExe) and put a shortcut to it in
    the current user's Startup folder, so the tray icon starts at login.
.PARAMETER TrayExe
    Path to maarse-tray.exe (default: target\release\maarse-tray.exe).
.PARAMETER Server
    Install maarse-server instead (default exe target\release\maarse-server.exe,
    folders and task named maarse-server, and a firewall rule for TCP 4242).
    Give its public address in -HostArgs, e.g. '--public-addr backbone.example.org:4242'.
.PARAMETER Uninstall
    Stop and remove the task and the tray shortcut (the data folder is kept).
#>
[CmdletBinding()]
param(
    [string]$Exe = "target\release\maarse-host.exe",
    [string]$InstallDir = "$env:ProgramFiles\maarse-host",
    [string]$DataDir = "$env:ProgramData\maarse-host",
    [string]$HostArgs = "",
    [string]$TaskName = "maarse-host",
    [switch]$Tray,
    [string]$TrayExe = "target\release\maarse-tray.exe",
    [switch]$Server,
    [switch]$Uninstall
)

# The program to install: maarse-host, or maarse-server with its own defaults.
$Prog = "maarse-host"
if ($Server) {
    $Prog = "maarse-server"
    if (-not $PSBoundParameters.ContainsKey("Exe")) { $Exe = "target\release\maarse-server.exe" }
    if (-not $PSBoundParameters.ContainsKey("InstallDir")) { $InstallDir = "$env:ProgramFiles\maarse-server" }
    if (-not $PSBoundParameters.ContainsKey("DataDir")) { $DataDir = "$env:ProgramData\maarse-server" }
    if (-not $PSBoundParameters.ContainsKey("TaskName")) { $TaskName = "maarse-server" }
}

$ErrorActionPreference = "Stop"

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw "Run this script from an elevated (administrator) PowerShell."
}

function Stop-HostTask {
    if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
        Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    }
    # Stopping the task ends the supervisor; make sure the host goes too.
    $target = Join-Path $InstallDir "$Prog.exe"
    Get-Process $Prog -ErrorAction SilentlyContinue |
        Where-Object { $_.Path -eq $target } |
        Stop-Process -Force -ErrorAction SilentlyContinue
}

$trayLink = Join-Path ([Environment]::GetFolderPath("Startup")) "maarse-tray.lnk"

if ($Uninstall) {
    Get-Process maarse-tray -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    Remove-Item -Force $trayLink -ErrorAction SilentlyContinue
    Stop-HostTask
    if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    }
    Write-Host "Removed task '$TaskName'. Data in $DataDir and files in $InstallDir were kept."
    return
}

if (-not (Test-Path $Exe)) {
    throw "$Prog.exe not found at '$Exe'. Build it with: cargo build --release -p maarse-host"
}

Stop-HostTask
New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
New-Item -ItemType Directory -Force -Path $DataDir | Out-Null
Copy-Item -Force $Exe (Join-Path $InstallDir "$Prog.exe")
if ($Server -and -not (Get-NetFirewallRule -DisplayName "maarse-server" -ErrorAction SilentlyContinue)) {
    New-NetFirewallRule -DisplayName "maarse-server" -Direction Inbound -Protocol TCP -LocalPort 4242 -Action Allow | Out-Null
    Write-Host "Firewall: inbound TCP 4242 allowed (rule 'maarse-server')"
}

# Supervisor: restart on non-zero exit, log to <data>\logs\host.log.
$supervisor = Join-Path $InstallDir "run-host.ps1"
$escapedArgs = $HostArgs.Replace("'", "''")
@"
# Generated by install-service.ps1. Starts $Prog and restarts it on failure.
`$ErrorActionPreference = 'Continue'
`$exe = Join-Path `$PSScriptRoot '$Prog.exe'
`$data = '$($DataDir.Replace("'", "''"))'
`$extra = '$escapedArgs'
`$logDir = Join-Path `$data 'logs'
New-Item -ItemType Directory -Force -Path `$logDir | Out-Null
`$log = Join-Path `$logDir 'host.log'
while (`$true) {
    if ((Test-Path `$log) -and (Get-Item `$log).Length -gt 10MB) {
        Move-Item -Force `$log "`$log.1"
    }
    Add-Content -Path `$log -Value "=== `$(Get-Date -Format s) starting $Prog"
    `$argLine = "--service --data ```"`$data```" `$extra"
    `$p = Start-Process -FilePath `$exe -ArgumentList `$argLine -WorkingDirectory `$data ``
        -NoNewWindow -PassThru -Wait ``
        -RedirectStandardOutput "`$log.out" -RedirectStandardError "`$log.err"
    Get-Content "`$log.out", "`$log.err" -ErrorAction SilentlyContinue | Add-Content -Path `$log
    Add-Content -Path `$log -Value "=== `$(Get-Date -Format s) $Prog exited with code `$(`$p.ExitCode)"
    if (`$p.ExitCode -eq 0) { break }
    Start-Sleep -Seconds 3
}
"@ | Set-Content -Encoding UTF8 -Path $supervisor

$action = New-ScheduledTaskAction -Execute "powershell.exe" `
    -Argument "-NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$supervisor`"" `
    -WorkingDirectory $DataDir
$trigger = New-ScheduledTaskTrigger -AtStartup
$runAs = New-ScheduledTaskPrincipal -UserId "SYSTEM" -LogonType ServiceAccount -RunLevel Highest
# No time limit; if the supervisor itself dies, Task Scheduler retries it.
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -MultipleInstances IgnoreNew

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
    -Principal $runAs -Settings $settings -Force | Out-Null
Start-ScheduledTask -TaskName $TaskName

if ($Tray) {
    if (-not (Test-Path $TrayExe)) {
        throw "maarse-tray.exe not found at '$TrayExe'. Build it with: cargo build --release -p maarse-tray"
    }
    Get-Process maarse-tray -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    $trayTarget = Join-Path $InstallDir "maarse-tray.exe"
    Copy-Item -Force $TrayExe $trayTarget
    $shell = New-Object -ComObject WScript.Shell
    $lnk = $shell.CreateShortcut($trayLink)
    $lnk.TargetPath = $trayTarget
    $lnk.Arguments = "--task `"$TaskName`" --data `"$DataDir`" --install-dir `"$InstallDir`""
    $lnk.Description = "Maarse host tray icon"
    $lnk.Save()
    # Not started from here: this shell is elevated and the tray should not be.
    Write-Host "Tray app added to Startup: $trayLink (starts at next login, or open the shortcut)"
}

Write-Host "Installed and started task '$TaskName'."
Write-Host "  Exe:  $(Join-Path $InstallDir "$Prog.exe")"
Write-Host "  Data: $DataDir"
Write-Host "  Log:  $(Join-Path $DataDir 'logs\host.log')"
Write-Host "Web client: http://127.0.0.1:8080/ (unless --http was changed)."
